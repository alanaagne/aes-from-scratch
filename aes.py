RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]


# FUNÇÕES AUXILIARES DE MATRIZ E GALOIS FIELD (GF(2^8))

def bytes_para_matriz(dados: bytes):
    """Converte 16 bytes em uma matriz 4x4 (State) em ordem de coluna (column-major)."""
    return [list(dados[i:i + 4]) for i in range(0, 16, 4)]


def matriz_para_bytes(matriz):
    """Converte uma matriz 4x4 de volta para uma sequência de 16 bytes."""
    dados = bytearray()
    for col in range(4):
        for lin in range(4):
            dados.append(matriz[lin][col])
    return bytes(dados)


def gmul(a, b):
    """Multiplicação no Campo de Galois GF(2^8) usando o polinômio redutor 0x11B."""
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi_bit_set = a & 0x80
        a = (a << 1) & 0xFF
        if hi_bit_set:
            a ^= 0x1B
        b >>= 1
    return p


# EXPANSÃO DE CHAVE (KeyExpansion)

def key_expansion(chave_16_bytes: bytes):
    """Expande a chave original de 16 bytes em 11 subchaves de rodada (44 palavras de 4 bytes)."""
    palavras = list(chave_16_bytes)

    for i in range(4, 44):
        temp = palavras[(i - 1) * 4: i * 4]

        if i % 4 == 0:
            # RotWord: Rotaciona à esquerda [a0, a1, a2, a3] -> [a1, a2, a3, a0]
            temp = temp[1:] + temp[:1]
            # SubWord: Substitui os bytes usando a S-Box
            temp = [SBOX[b] for b in temp]
            # Aplica Rcon no primeiro byte da palavra
            temp[0] ^= RCON[i // 4]

        palavra_anterior = palavras[(i - 4) * 4: (i - 3) * 4]
        nova_palavra = [p ^ t for p, t in zip(palavra_anterior, temp)]
        palavras.extend(nova_palavra)

    # Organiza em 11 matrizes 4x4 para cada uma das rodadas (0 a 10)
    chaves_rodada = []
    for r in range(11):
        bloco = palavras[r * 16: (r + 1) * 16]
        matriz = [[bloco[c * 4 + l] for c in range(4)] for l in range(4)]
        chaves_rodada.append(matriz)

    return chaves_rodada


# ETAPAS DA CIFRAGEM

def add_round_key(estado, chave_rodada):
    """Realiza a operação XOR byte a byte entre a matriz de estado e a chave da rodada."""
    for l in range(4):
        for c in range(4):
            estado[l][c] ^= chave_rodada[l][c]


def sub_bytes(estado):
    """Substitui cada byte da matriz de estado pelo correspondente na S-Box."""
    for l in range(4):
        for c in range(4):
            estado[l][c] = SBOX[estado[l][c]]


def shift_rows(estado):
    """Desloca os bytes das linhas da matriz para a esquerda: linha i desloca i posições."""
    estado[1] = estado[1][1:] + estado[1][:1]
    estado[2] = estado[2][2:] + estado[2][:2]
    estado[3] = estado[3][3:] + estado[3][:3]


def mix_columns(estado):
    """Combina os elementos de cada coluna usando a multiplicação em GF(2^8)."""
    for c in range(4):
        col = [estado[l][c] for l in range(4)]
        estado[0][c] = gmul(col[0], 2) ^ gmul(col[1], 3) ^ col[2] ^ col[3]
        estado[1][c] = col[0] ^ gmul(col[1], 2) ^ gmul(col[2], 3) ^ col[3]
        estado[2][c] = col[0] ^ col[1] ^ gmul(col[2], 2) ^ gmul(col[3], 3)
        estado[3][c] = gmul(col[0], 3) ^ col[1] ^ col[2] ^ gmul(col[3], 2)


# ETAPAS DA DECIFRAGEM (OPERAÇÕES INVERSAS)

def inv_sub_bytes(estado):
    """Substitui cada byte usando a Inv S-Box."""
    for l in range(4):
        for c in range(4):
            estado[l][c] = INV_SBOX[estado[l][c]]


def inv_shift_rows(estado):
    """Desloca os bytes das linhas da matriz para a direita."""
    estado[1] = estado[1][-1:] + estado[1][:-1]
    estado[2] = estado[2][-2:] + estado[2][:-2]
    estado[3] = estado[3][-3:] + estado[3][:-3]


def inv_mix_columns(estado):
    """Aplica a matriz inversa do MixColumns em GF(2^8)."""
    for c in range(4):
        col = [estado[l][c] for l in range(4)]
        estado[0][c] = gmul(col[0], 14) ^ gmul(col[1], 11) ^ gmul(col[2], 13) ^ gmul(col[3], 9)
        estado[1][c] = gmul(col[0], 9) ^ gmul(col[1], 14) ^ gmul(col[2], 11) ^ gmul(col[3], 13)
        estado[2][c] = gmul(col[0], 13) ^ gmul(col[1], 9) ^ gmul(col[2], 14) ^ gmul(col[3], 11)
        estado[3][c] = gmul(col[0], 11) ^ gmul(col[1], 13) ^ gmul(col[2], 9) ^ gmul(col[3], 14)


# ALGORITMO PRINCIPAL (EAX / ECB BLOCKS DE 16 BYTES)

def aes_encrypt_block(bloco_16_bytes: bytes, chave_16_bytes: bytes) -> bytes:
    """Cifra um único bloco de 16 bytes usando o algoritmo AES-128."""
    if len(bloco_16_bytes) != 16 or len(chave_16_bytes) != 16:
        raise ValueError("O bloco e a chave devem ter exatamente 16 bytes (128 bits).")

    # Mapeia bytes de entrada para matriz de estado 4x4 invertida (column-major)
    estado = [[0] * 4 for _ in range(4)]
    for l in range(4):
        for c in range(4):
            estado[l][c] = bloco_16_bytes[c * 4 + l]

    chaves_rodada = key_expansion(chave_16_bytes)

    # Rodada Inicial (Round 0)
    add_round_key(estado, chaves_rodada[0])

    # Rodadas Principais (1 a 9)
    for r in range(1, 10):
        sub_bytes(estado)
        shift_rows(estado)
        mix_columns(estado)
        add_round_key(estado, chaves_rodada[r])

    # Rodada Final (Round 10) - Sem MixColumns
    sub_bytes(estado)
    shift_rows(estado)
    add_round_key(estado, chaves_rodada[10])

    return matriz_para_bytes(estado)


def aes_decrypt_block(bloco_cifrado: bytes, chave_16_bytes: bytes) -> bytes:
    """Decifra um único bloco de 16 bytes usando o algoritmo AES-128."""
    if len(bloco_cifrado) != 16 or len(chave_16_bytes) != 16:
        raise ValueError("O bloco e a chave devem ter exatamente 16 bytes (128 bits).")

    estado = [[0] * 4 for _ in range(4)]
    for l in range(4):
        for c in range(4):
            estado[l][c] = bloco_cifrado[c * 4 + l]

    chaves_rodada = key_expansion(chave_16_bytes)

    # Rodada Inicial Inversa (Round 10)
    add_round_key(estado, chaves_rodada[10])

    # Rodadas Inversas (9 até 1)
    for r in range(9, 0, -1):
        inv_shift_rows(estado)
        inv_sub_bytes(estado)
        add_round_key(estado, chaves_rodada[r])
        inv_mix_columns(estado)

    # Rodada Final Inversa (Round 0)
    inv_shift_rows(estado)
    inv_sub_bytes(estado)
    add_round_key(estado, chaves_rodada[0])

    return matriz_para_bytes(estado)